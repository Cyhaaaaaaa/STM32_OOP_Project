// App/main.c
#include "delay.h"         // 底层心跳服务（时间基准）
#include "misc.h"          // NVIC 优先级分组配置（芯片级全局配置）
#include "app_lighting.h"  // 灯光业务组件
#include "notifier.h"      // 系统事件总线（启动 1 秒心跳广播）
#include "workqueue.h"     // 事件驱动调度器（主循环唯一要做的事）

/*
 * 事件驱动版入口 —— 和轮询版最大的区别在 while(1) 里。
 *
 * 轮询版的主循环：
 *   while (1) {
 *       App_Lighting_Task();   // 每圈问一次"到点没"
 *       App_Key_Task();        // 每圈问一次
 *       App_Sensor_Task();     // 每圈问一次 ...
 *   }
 *
 * 事件版的主循环：
 *   while (1) {
 *       run_workqueue();       // 只有"到点的任务"才会被叫醒
 *   }
 *
 * 所有模块都在各自的 Init() 里把自己"挂"成了 workqueue 任务，
 * 或订阅了系统事件。main 不需要知道有多少个模块、每个模块该多久跑一次——
 * 它只知道"有延迟任务到点了，就去跑一下"。这就是事件驱动：调度权从
 * 主循环的"主动轮询"转移到了每个任务自己的"按需唤醒"。
 */

int main(void) {
    /* ========================================== */
    /* 1. 全局系统与内核级服务初始化              */
    /* ========================================== */

    // 配置 NVIC 中断优先级分组（必须在所有外设初始化之前调用）
    NVIC_PriorityGroupConfig(NVIC_PriorityGroup_2);

    // 启动 1ms 系统心跳，这是所有时间判断的基准
    Delay_Init();

    // 启动系统事件总线（内部用 workqueue 每秒广播一次 SYS_EVT_SECOND）
    sys_event_init();

    /* ========================================== */
    /* 2. 各个业务组件 (App 层) 初始化            */
    /* ========================================== */
    App_Lighting_Init();
    // 未来加新模块，也只需要一行 Init，然后它就"自驱动"了

    /* ========================================== */
    /* 3. 主调度循环 —— 只剩一件事：跑 workqueue  */
    /* ========================================== */
    while (1) {
        run_workqueue();   // 处理所有到点的延迟任务，其余时间什么也不干
    }
}
